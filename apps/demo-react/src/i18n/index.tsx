export type Translations = typeof translations.en;

interface I18nContextValue {
  locale: Locale;
  t: Translations;
  setLocale: (locale: Locale) => void;
  toggleLocale: () => void;
  format: (template: string, vars: Record<string, string | number>) => string;
  getProductName: (product: Product) => string;
  getProductDescription: (product: Product) => string;
  formatPrice: (price: number) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const getInitialLocale = (): Locale => {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('owllayer_demo_lang');
    if (saved === 'en' || saved === 'fr') return saved;
  }
  const envLang = import.meta.env.VITE_APP_LANGUAGE;
  if (envLang === 'fr' || envLang === 'en') return envLang;
  return 'en';
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('owllayer_demo_lang', newLocale);
    }
  };

  const toggleLocale = () => {
    setLocale(locale === 'en' ? 'fr' : 'en');
  };

  const t = translations[locale] ?? translations.en;

  const format = (template: string, vars: Record<string, string | number>): string => {
    return Object.entries(vars).reduce(
      (res, [k, v]) => res.replaceAll(`{${k}}`, String(v)),
      template
    );
  };

  const getProductName = (product: Product): string => {
    const localized = t.productItems?.[product.id];
    return localized?.name || product.name;
  };

  const getProductDescription = (product: Product): string => {
    const localized = t.productItems?.[product.id];
    return localized?.description || product.description;
  };

  const formatPrice = (price: number): string => {
    if (locale === 'fr') {
      return `${price.toFixed(2)} €`;
    }
    return `$${price.toFixed(2)}`;
  };

  return (
    <I18nContext.Provider
      value={{
        locale,
        t,
        setLocale,
        toggleLocale,
        format,
        getProductName,
        getProductDescription,
        formatPrice,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return ctx;
}
